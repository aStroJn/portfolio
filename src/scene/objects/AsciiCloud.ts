export interface AsciiCloudOptions {
  text?: string;
  x: number;
  y: number;
  scale?: number;
  alpha?: number;
  color?: string | number;
}

export class AsciiCloud extends Container {
  private readonly textSprite: Text;

  constructor(options: AsciiCloudOptions) {
    super();

    const style = new TextStyle({
      fontFamily: '"Courier New", Consolas, Courier, monospace',
      fontSize: 8.5,
      lineHeight: 7.2,
      letterSpacing: 0,
      // Sunset glow colors matching the sky palette
      fill: options.color ?? 0xfb7185,
    });

    this.textSprite = new Text({
      text: options.text ?? ASCII_BLOCK_CLOUD,
      style,
    });

    this.addChild(this.textSprite);
    this.position.set(options.x, options.y);
    const s = options.scale ?? 1;
    this.scale.set(s);
    this.alpha = options.alpha ?? 0.6;
    // Screen blend mode illuminates the sunset gradient naturally
    this.blendMode = 'screen';
  }
}
